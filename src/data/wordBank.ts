export function getWordLength(word: string): number {
  return word.length;
}

export function getDifficultyLevel(word: string): 'easy' | 'medium' | 'hard' {
  const len = word.length;
  if (len <= 4) return 'easy';
  if (len <= 6) return 'medium';
  return 'hard';
}

export function getWordsByMaxLength(maxLen: number): WordEntry[] {
  return wordBank.filter(w => w.en.length <= maxLen);
}

export function getWordsByLength(len: number): WordEntry[] {
  return wordBank.filter(w => w.en.length === len);
}

export function getWordsByDifficulty(level: number): WordEntry[] {
  if (level <= 2) return wordBank.filter(w => w.en.length <= 4);
  if (level <= 4) return wordBank.filter(w => w.en.length >= 4 && w.en.length <= 5);
  if (level <= 6) return wordBank.filter(w => w.en.length >= 5 && w.en.length <= 6);
  if (level <= 8) return wordBank.filter(w => w.en.length >= 6 && w.en.length <= 7);
  return wordBank.filter(w => w.en.length >= 7);
}
